export function getMetroCoordinates(regionName, stateName) {
  // Direct lookup
  if (METRO_COORDINATES[regionName]) {
    return METRO_COORDINATES[regionName];
  }

  // Try matching by city name from "City, ST" format
  const cityMatch = regionName.match(/^(.+?),\s*(\w{2})$/);
  if (cityMatch) {
    const state = cityMatch[2];
    // Fall back to state centroid with slight random offset to avoid stacking
    if (STATE_CENTROIDS[state]) {
      const offset = () => (Math.random() - 0.5) * 0.5;
      return {
        lat: STATE_CENTROIDS[state].lat + offset(),
        lng: STATE_CENTROIDS[state].lng + offset(),
      };
    }
  }

  // Try stateName field
  if (stateName && STATE_CENTROIDS[stateName]) {
    const offset = () => (Math.random() - 0.5) * 0.5;
    return {
      lat: STATE_CENTROIDS[stateName].lat + offset(),
      lng: STATE_CENTROIDS[stateName].lng + offset(),
    };
  }

  return null;
}
